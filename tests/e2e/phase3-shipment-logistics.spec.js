test('shipment POD and discrepancy persist and duplicate POD is rejected', async ({ page }) => {
  await loginAs(page, 'Logistics Coordinator')
  await seedPackedBuyerPO(page)
  await page.goto('/logistics/shipment-planning')
  await page.getByRole('button', { name: 'Create shipment' }).click()
  await page.getByLabel('Purchase order').selectOption('2')
  await page.getByLabel('Packed quantity').fill('100')
  await page.getByLabel('Tracking number').fill('E2E-SHP-POD')
  await page.getByLabel('Transaction reference').fill('E2E-SHP-TX-POD')
  const beforeShipment = await page.evaluate(() => { const state = JSON.parse(localStorage.getItem('phsardom-erpv1') || '{}'); return { inventory: state.inventoryOps, invoices: state.invoices } })
  await page.getByRole('button', { name: 'Create shipment' }).last().click()
  const created = await page.evaluate(() => JSON.parse(localStorage.getItem('phsardom-erpv1') || '{}'))
  const shipment = created.shipments.find((row) => row.transactionId === 'E2E-SHP-TX-POD')
  await page.goto(`/logistics/shipments/${shipment.shipmentId}`)
  await page.getByRole('button', { name: 'Dispatch shipment' }).click()
  await page.getByRole('button', { name: 'Mark in transit' }).click()
  await page.getByRole('button', { name: 'Confirm delivery / POD' }).click()
  await page.getByLabel('Receiver name').fill('Atlas Receiving')
  await page.getByLabel('Delivered quantity').fill('80')
  await page.getByLabel('Delivery date').fill('2026-10-28')
  await page.getByRole('button', { name: 'Save POD' }).click()
  await expect(page.getByText(/delivery recorded/i)).toBeVisible()
  const afterPod = await page.evaluate(() => JSON.parse(localStorage.getItem('phsardom-erpv1') || '{}'))
  const stored = afterPod.shipments.find((row) => row.shipmentId === shipment.shipmentId)
  expect(stored.deliveredQuantity).toBe(80)
  expect(afterPod.inventoryOps).toEqual(beforeShipment.inventory)
  expect(afterPod.invoices).toEqual(beforeShipment.invoices)
  expect(afterPod.audit.filter((entry) => entry.action === 'SHIPMENT_PARTIALLY_DELIVERED')).toHaveLength(1)
  await page.getByRole('button', { name: 'Record discrepancy' }).click()
  await page.getByLabel('Reference').fill('E2E-DISC-1')
  await page.getByLabel('Missing quantity').fill('10')
  await page.getByLabel('Damaged quantity').fill('5')
  await page.getByLabel('Reason').fill('Short and damaged cartons')
  await page.getByRole('button', { name: 'Save discrepancy' }).click()
  await expect(page.getByText(/discrepancy recorded/i)).toBeVisible()
  const discrepancyState = await page.evaluate(() => JSON.parse(localStorage.getItem('phsardom-erpv1') || '{}'))
  const discrepancyShipment = discrepancyState.shipments.find((row) => row.shipmentId === shipment.shipmentId)
  expect(discrepancyShipment.discrepancyRecords).toEqual(expect.arrayContaining([expect.objectContaining({ reference: 'E2E-DISC-1', missingQuantity: 10, damagedQuantity: 5 })]))
  expect(discrepancyState.audit.some((entry) => entry.action === 'SHIPMENT_DISCREPANCY_RECORDED' && entry.entityId === shipment.shipmentId)).toBe(true)
  await page.reload()
  await expect(page.getByText('Audit timeline')).toBeVisible()
  await expect(page.getByText('SHIPMENT_PARTIALLY_DELIVERED')).toBeVisible()
  await expect(page.getByText('E2E-DISC-1')).toBeVisible()
  await page.getByRole('button', { name: 'Confirm delivery / POD' }).click()
  await page.getByLabel('Receiver name').fill('Duplicate Receiver')
  await page.getByLabel('Delivered quantity').fill('1')
  await page.getByLabel('Delivery date').fill('2026-10-28')
  await page.getByRole('button', { name: 'Save POD' }).click()
  await expect(page.getByRole('status')).toContainText(/proof|submitted|delivery/i)
  const duplicateAttempt = await page.evaluate(() => JSON.parse(localStorage.getItem('phsardom-erpv1') || '{}'))
  expect(duplicateAttempt.audit.filter((entry) => entry.action === 'SHIPMENT_PARTIALLY_DELIVERED')).toHaveLength(1)
})

test('one PO supports two partial shipments and rejects allocation beyond packed remainder', async ({ page }) => {
  await loginAs(page, 'Logistics Coordinator')
  await seedPackedBuyerPO(page)
  await page.goto('/logistics/shipment-planning')
  const create = async (quantity, tracking, reference) => {
    await page.getByRole('button', { name: 'Create shipment' }).click()
    await page.getByLabel('Purchase order').selectOption('2')
    await page.getByLabel('Packed quantity').fill(String(quantity))
    await page.getByLabel('Tracking number').fill(tracking)
    await page.getByLabel('Transaction reference').fill(reference)
    await page.getByRole('button', { name: 'Create shipment' }).last().click()
    await expect(page.getByText(/created and ready to dispatch/i)).toBeVisible()
  }
  await create(100, 'E2E-SHP-A', 'E2E-TX-A')
  await create(200, 'E2E-SHP-B', 'E2E-TX-B')
  const state = await page.evaluate(() => JSON.parse(localStorage.getItem('phsardom-erpv1') || '{}'))
  const shipments = state.shipments.filter((row) => ['E2E-TX-A', 'E2E-TX-B'].includes(row.transactionId))
  expect(shipments).toHaveLength(2)
  expect(new Set(shipments.map((row) => row.shipmentId)).size).toBe(2)
  expect(new Set(shipments.map((row) => row.poId)).size).toBe(1)
  expect(shipments.reduce((sum, row) => sum + row.packedQuantity, 0)).toBe(300)
  await page.getByRole('button', { name: 'Create shipment' }).click()
  await page.getByLabel('Purchase order').selectOption('2')
  await page.getByLabel('Packed quantity').fill('701')
  await page.getByLabel('Tracking number').fill('E2E-SHP-C')
  await page.getByLabel('Transaction reference').fill('E2E-TX-C')
  await page.getByRole('button', { name: 'Create shipment' }).last().click()
  await expect(page.getByRole('status')).toContainText(/packed|quantity|exceed/i)
  await page.reload()
  const persisted = await page.evaluate(() => JSON.parse(localStorage.getItem('phsardom-erpv1') || '{}'))
  expect(persisted.shipments.filter((row) => ['E2E-TX-A', 'E2E-TX-B'].includes(row.transactionId))).toHaveLength(2)
})

