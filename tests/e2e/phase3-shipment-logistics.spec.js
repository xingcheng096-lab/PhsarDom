import { expect, test } from '@playwright/test'

async function loginAs(page, label) {
  await page.goto('/login')
  await page.evaluate(() => localStorage.removeItem('phsardom-session'))
  await page.getByRole('button', { name: `Login as ${label}` }).click()
}

async function seedPackedBuyerPO(page) {
  await page.evaluate(() => {
    const raw = JSON.parse(localStorage.getItem('phsardom-erpv1') || '{}')
    raw.purchaseOrders = (raw.purchaseOrders || []).map((po) => po.number === 'PO-2026-2141' ? { ...po, buyerId: 1 } : po)
    raw.packing = [...(raw.packing || []).filter((row) => row.po !== 'PO-2026-2141'), { id: 'E2E-PACK-2141', po: 'PO-2026-2141', sku: 'FURN-ERG8', status: 'Ready to Ship', packed: 500, qty: 500 }]
    localStorage.setItem('phsardom-erpv1', JSON.stringify(raw))
  })
  await page.reload()
}

test('logistics creates and dispatches a shipment from packed PO with persistence', async ({ page }) => {
  await loginAs(page, 'Logistics Coordinator')
  await seedPackedBuyerPO(page)
  await page.goto('/logistics/shipment-planning')
  await page.getByRole('button', { name: 'Create shipment' }).click()
  await page.getByLabel('Purchase order').selectOption('2')
  await page.getByLabel('Packed quantity').fill('100')
  await page.getByLabel('Tracking number').fill('E2E-SHP-100')
  await page.getByLabel('Transaction reference').fill('E2E-SHP-TX-100')
  await page.getByRole('button', { name: 'Create shipment' }).last().click()
  await expect(page.getByText(/created and ready to dispatch/i)).toBeVisible()
  const state = await page.evaluate(() => JSON.parse(localStorage.getItem('phsardom-erpv1') || '{}'))
  const shipment = state.shipments.find((row) => row.transactionId === 'E2E-SHP-TX-100')
  expect(shipment).toMatchObject({ poId: 2, buyerId: 1, packedQuantity: 100, status: 'Ready to Dispatch' })
  expect(state.audit.some((entry) => entry.action === 'SHIPMENT_CREATED' && entry.actor?.role === 'logistics')).toBe(true)
  await page.goto(`/logistics/shipments/${shipment.shipmentId}`)
  await page.getByRole('button', { name: 'Dispatch shipment' }).click()
  expect((await page.evaluate(() => JSON.parse(localStorage.getItem('phsardom-erpv1') || '{}'))).shipments[0].status).toBe('Dispatched')
  await page.reload()
  await expect(page.getByText('Dispatched').first()).toBeVisible()
})

