import { expect, test } from '@playwright/test'

async function loginAs(page, label, buyerBusiness) {
  await page.goto('/login')
  await page.evaluate(() => localStorage.removeItem('phsardom-session'))
  if (buyerBusiness) {
    const selector = page.getByLabel(/Demo buyer account/)
    const value = await selector.locator('option').filter({ hasText: buyerBusiness }).getAttribute('value')
    await selector.selectOption(value)
  }
  await page.getByRole('button', { name: `Login as ${label}` }).click()
}

test('new buyer completes the visible RFQ to PO journey', async ({ page }) => {
  const business = `Journey Buyer ${Date.now()}`
  await page.goto('/register')
  await page.getByLabel('Legal business name').fill(business)
  await page.getByLabel('Tax ID').fill(`TX-${Date.now()}`)
  await page.getByLabel('Business email').fill(`buyer-${Date.now()}@example.test`)
  await page.getByLabel('Contact name').fill('Journey Buyer')
  await page.getByLabel('Password').fill('Password123!')
  await page.getByRole('button', { name: /Continue/i }).click()
  await page.getByLabel('Business address').fill('1 Demo Street')
  await page.getByLabel('Phone').fill('+855 12345678')
  await page.locator('input[type="file"]').setInputFiles({ name: 'kyc.pdf', mimeType: 'application/pdf', buffer: Buffer.from('demo kyc') })
  await page.getByRole('checkbox').check()
  await page.getByRole('button', { name: /Submit for verification/i }).click()
  await expect(page).toHaveURL(/pending-approval/)
  const buyer = await page.evaluate((name) => JSON.parse(localStorage.getItem('meridian-demo-buyers') || '[]').find((row) => row.business === name), business)
  expect(buyer).toMatchObject({ business, status: 'Pending', kycStatus: 'Pending' })

  await loginAs(page, 'Super Admin')
  await page.goto(`/admin/buyers/${buyer.id}`)
  await page.getByRole('button', { name: 'Approve Buyer' }).click()
  await page.getByRole('button', { name: 'Approve', exact: true }).last().click()
  await expect(page.getByText(/approved and verified/i)).toBeVisible()
  const approved = await page.evaluate((id) => JSON.parse(localStorage.getItem('meridian-demo-buyers') || '[]').find((row) => String(row.id) === String(id)), buyer.id)
  expect(approved.status).toBe('Approved')

  await loginAs(page, 'Verified Buyer', business)
  const session = await page.evaluate(() => JSON.parse(localStorage.getItem('phsardom-session') || 'null'))
  expect(session).toMatchObject({ buyerId: buyer.id, buyerBusiness: business, buyerStatus: 'Approved' })
  await page.goto('/buyer/rfqs/new')
  await page.getByLabel('Product').selectOption({ label: 'Commercial Surface Cleaner 5L' })
  await page.getByLabel('Required quantity').fill('24')
  await page.getByLabel('Required delivery date').fill('2099-10-01')
  await page.getByLabel('Shipping location').fill('Phnom Penh')
  await page.getByRole('button', { name: /submit rfq/i }).click()
  await expect(page).toHaveURL(/\/buyer\/rfqs$/)
  const rfq = await page.evaluate((id) => JSON.parse(localStorage.getItem('meridian-demo-rfqs') || '[]').find((row) => String(row.buyerId) === String(id)), buyer.id)
  expect(rfq).toMatchObject({ buyerId: buyer.id, buyer: business, quantity: 24 })

  await loginAs(page, 'Account Executive')
  await page.goto('/sales/quotations/new')
  await page.locator('select[name="buyer"]').selectOption({ label: business })
  await page.locator('select[name="rfq"]').selectOption({ label: `${rfq.number} - ${rfq.product} · ${rfq.buyer}` })
  await page.getByLabel('Validity date').fill('2099-12-31')
  await page.getByRole('button', { name: /Create and send quotation/i }).click()
  await expect(page).toHaveURL(/\/sales\/quotations$/)
  const quote = await page.evaluate((rfqNumber) => JSON.parse(localStorage.getItem('meridian-demo-quotations') || '[]').find((row) => row.rfq === rfqNumber), rfq.number)
  expect(quote).toMatchObject({ buyerId: buyer.id, buyer: business, rfq: rfq.number })

  await loginAs(page, 'Verified Buyer', business)
  await page.goto(`/buyer/quotations/${quote.id}`)
  await page.getByRole('button', { name: 'Counter Offer' }).click()
  await page.getByLabel('Proposed unit price (USD)').fill('80')
  await page.getByLabel('Quantity').fill('24')
  await page.getByRole('button', { name: 'Confirm' }).click()
  await expect(page.getByText('Counter offer submitted. Counteroffer saved and sent to sales.')).toBeVisible()
  const countered = await page.evaluate((id) => JSON.parse(localStorage.getItem('meridian-demo-quotations') || '[]').find((row) => row.id === id), quote.id)
  expect(countered.negotiations.at(-1)).toMatchObject({ status: 'Countered', actorId: buyer.id })

  await loginAs(page, 'Account Executive')
  await page.goto(`/sales/quotations/${quote.id}`)
  await page.getByRole('button', { name: 'Request Revision' }).click()
  await expect(page.getByText('Revised quotation saved and sent to buyer.')).toBeVisible()
  const revised = await page.evaluate((id) => JSON.parse(localStorage.getItem('meridian-demo-quotations') || '[]').find((row) => row.id === id), quote.id)
  expect(revised.negotiations.length).toBeGreaterThan(countered.negotiations.length)

  await loginAs(page, 'Verified Buyer', business)
  await page.goto(`/buyer/quotations/${quote.id}`)
  await page.getByRole('button', { name: 'Accept Quote' }).click()
  await page.getByRole('button', { name: 'Accept Quote', exact: true }).last().click()
  await expect(page.getByText(/Purchase order .* created/i)).toBeVisible()
  const persisted = await page.evaluate((id) => ({ quote: JSON.parse(localStorage.getItem('meridian-demo-quotations') || '[]').find((row) => row.id === id), pos: JSON.parse(localStorage.getItem('meridian-demo-purchaseOrders') || '[]') }), quote.id)
  const po = persisted.pos.find((row) => row.quote === persisted.quote.number)
  expect(persisted.quote).toMatchObject({ status: 'Accepted', buyerId: buyer.id, rfq: rfq.number })
  expect(po).toMatchObject({ buyer: business, quote: persisted.quote.number, rfq: rfq.number, product: rfq.product, quantity: rfq.quantity })
})
